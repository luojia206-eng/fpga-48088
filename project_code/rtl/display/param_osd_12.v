`timescale 1ns/1ps

// Parameter banner: volume and brightness levels rendered from a 12x12 glyph
// ROM as four CJK characters plus digits, i.e. U+97F3 U+91CF <n> / 5 then
// U+4EAE U+5EA6 <n> / 4. ASCII comments only: iverilog reads this file as ANSI
// and multi-byte characters inside comments break its parser.
//
// The status OSD uses a tiny 5x7 font that can only show one letter per cell;
// Chinese labels need a real glyph ROM, so this is a separate overlay stage in
// the same style as the scrolling subtitle (registered read, whole timing
// bundle delayed by one clock so the HDMI data-island alignment is preserved).
//
// Glyph map (order of the ROM, generated by tools\gen_subtitle_rom.ps1 with
// the text 音量亮度0123456789/):
//   0=音 1=量 2=亮 3=度 4..13='0'..'9' 14='/'
module param_osd_12 #(
    parameter integer OSD_X = 8,
    parameter integer OSD_Y = 24,
    parameter [23:0] TEXT_COLOR = 24'hFFD966
) (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        hsync,
    input  wire        vsync,
    input  wire        de,
    input  wire [9:0]  pixel_x,
    input  wire [23:0] rgb_in,
    // 1-based levels so the banner reads "音量3/5" rather than "音量2/5".
    input  wire [3:0]  vol_digit,
    input  wire [3:0]  bright_digit,
    output reg         hsync_out,
    output reg         vsync_out,
    output reg         de_out,
    output reg  [9:0]  pixel_x_out,
    output wire [23:0] rgb_out
);
    localparam integer GLYPH_W = 12;
    localparam integer GLYPH_H = 12;
    localparam integer GLYPH_STRIDE = 16;
    localparam integer CELLS = 11;
    localparam integer TEXT_W = GLYPH_STRIDE * CELLS;
    localparam [9:0]  OSD_X_R = OSD_X;
    localparam [11:0] OSD_Y_R = OSD_Y;
    localparam [3:0]  OSD_Y_ROW = OSD_Y % 16;

    reg [11:0] glyph_rom [0:179] /* fehdl force_ram=1, ram_style="bram" */;
    integer init_index;
    initial begin
        for (init_index = 0; init_index < 180; init_index = init_index + 1)
            glyph_rom[init_index] = 12'h000;

        // glyph U+97F3
        glyph_rom[0]=12'h040; glyph_rom[1]=12'h7FC;
        glyph_rom[2]=12'h208; glyph_rom[3]=12'h110;
        glyph_rom[4]=12'hFFE; glyph_rom[6]=12'h7FC;
        glyph_rom[7]=12'h404; glyph_rom[8]=12'h7FC;
        glyph_rom[9]=12'h404; glyph_rom[10]=12'h7FC;
        glyph_rom[11]=12'h404;

        // glyph U+91CF
        glyph_rom[12]=12'h7FC; glyph_rom[13]=12'h444;
        glyph_rom[14]=12'h424; glyph_rom[15]=12'hFFE;
        glyph_rom[16]=12'h444; glyph_rom[17]=12'h7FC;
        glyph_rom[18]=12'h444; glyph_rom[19]=12'h7FC;
        glyph_rom[20]=12'h040; glyph_rom[21]=12'h7FC;
        glyph_rom[22]=12'h040; glyph_rom[23]=12'hFFE;

        // glyph U+4EAE
        glyph_rom[24]=12'h040; glyph_rom[25]=12'hFFE;
        glyph_rom[27]=12'h3F8; glyph_rom[28]=12'h208;
        glyph_rom[29]=12'h3F8; glyph_rom[31]=12'hFFE;
        glyph_rom[32]=12'h802; glyph_rom[33]=12'h3F0;
        glyph_rom[34]=12'h212; glyph_rom[35]=12'hC0E;

        // glyph U+5EA6
        glyph_rom[36]=12'h020; glyph_rom[37]=12'h7FE;
        glyph_rom[38]=12'h488; glyph_rom[39]=12'h7FE;
        glyph_rom[40]=12'h488; glyph_rom[41]=12'h4F8;
        glyph_rom[42]=12'h400; glyph_rom[43]=12'h5FC;
        glyph_rom[44]=12'h484; glyph_rom[45]=12'h448;
        glyph_rom[46]=12'h430; glyph_rom[47]=12'h9CE;

        // glyph U+0030
        glyph_rom[50]=12'h0E0; glyph_rom[51]=12'h110;
        glyph_rom[52]=12'h110; glyph_rom[53]=12'h110;
        glyph_rom[54]=12'h110; glyph_rom[55]=12'h110;
        glyph_rom[56]=12'h110; glyph_rom[57]=12'h0E0;

        // glyph U+0031
        glyph_rom[62]=12'h040; glyph_rom[63]=12'h0C0;
        glyph_rom[64]=12'h040; glyph_rom[65]=12'h040;
        glyph_rom[66]=12'h040; glyph_rom[67]=12'h040;
        glyph_rom[68]=12'h040; glyph_rom[69]=12'h0E0;

        // glyph U+0032
        glyph_rom[74]=12'h0E0; glyph_rom[75]=12'h110;
        glyph_rom[76]=12'h110; glyph_rom[77]=12'h020;
        glyph_rom[78]=12'h040; glyph_rom[79]=12'h080;
        glyph_rom[80]=12'h100; glyph_rom[81]=12'h1F0;

        // glyph U+0033
        glyph_rom[86]=12'h0E0; glyph_rom[87]=12'h110;
        glyph_rom[88]=12'h010; glyph_rom[89]=12'h060;
        glyph_rom[90]=12'h010; glyph_rom[91]=12'h010;
        glyph_rom[92]=12'h110; glyph_rom[93]=12'h0E0;

        // glyph U+0034
        glyph_rom[98]=12'h020; glyph_rom[99]=12'h060;
        glyph_rom[100]=12'h060; glyph_rom[101]=12'h0A0;
        glyph_rom[102]=12'h120; glyph_rom[103]=12'h1F0;
        glyph_rom[104]=12'h020; glyph_rom[105]=12'h070;

        // glyph U+0035
        glyph_rom[110]=12'h1F0; glyph_rom[111]=12'h100;
        glyph_rom[112]=12'h100; glyph_rom[113]=12'h1E0;
        glyph_rom[114]=12'h110; glyph_rom[115]=12'h010;
        glyph_rom[116]=12'h110; glyph_rom[117]=12'h0E0;

        // glyph U+0036
        glyph_rom[122]=12'h060; glyph_rom[123]=12'h090;
        glyph_rom[124]=12'h100; glyph_rom[125]=12'h160;
        glyph_rom[126]=12'h190; glyph_rom[127]=12'h110;
        glyph_rom[128]=12'h110; glyph_rom[129]=12'h0E0;

        // glyph U+0037
        glyph_rom[134]=12'h0F0; glyph_rom[135]=12'h010;
        glyph_rom[136]=12'h020; glyph_rom[137]=12'h020;
        glyph_rom[138]=12'h040; glyph_rom[139]=12'h040;
        glyph_rom[140]=12'h040; glyph_rom[141]=12'h040;

        // glyph U+0038
        glyph_rom[146]=12'h0E0; glyph_rom[147]=12'h110;
        glyph_rom[148]=12'h110; glyph_rom[149]=12'h0E0;
        glyph_rom[150]=12'h110; glyph_rom[151]=12'h110;
        glyph_rom[152]=12'h110; glyph_rom[153]=12'h0E0;

        // glyph U+0039
        glyph_rom[158]=12'h0E0; glyph_rom[159]=12'h110;
        glyph_rom[160]=12'h110; glyph_rom[161]=12'h130;
        glyph_rom[162]=12'h0D0; glyph_rom[163]=12'h010;
        glyph_rom[164]=12'h120; glyph_rom[165]=12'h0C0;

        // glyph U+002F
        glyph_rom[169]=12'h008; glyph_rom[170]=12'h010;
        glyph_rom[171]=12'h010; glyph_rom[172]=12'h020;
        glyph_rom[173]=12'h020; glyph_rom[174]=12'h040;
        glyph_rom[175]=12'h040; glyph_rom[176]=12'h080;
        glyph_rom[177]=12'h080; glyph_rom[178]=12'h100;

    end

    reg [11:0] line_y;
    reg        de_q;
    reg        vs_q;

    wire [9:0] x_rel = pixel_x - OSD_X_R;
    wire in_band = de && (pixel_x >= OSD_X_R) &&
                   (pixel_x < OSD_X_R + TEXT_W) &&
                   (line_y >= OSD_Y_R) && (line_y < OSD_Y_R + GLYPH_H);
    wire [3:0] cell_idx = x_rel[7:4];
    wire [3:0] col  = x_rel[3:0];
    wire [3:0] row  = line_y[3:0] - OSD_Y_ROW;

    // Cell to glyph index:
    //   U+97F3, U+91CF, <vol>, '/', '5', gap, U+4EAE, U+5EA6, <bri>, '/', '4'
    reg [4:0] glyph_sel;
    reg       cell_valid;
    always @* begin
        glyph_sel  = 5'd8;
        cell_valid = 1'b1;
        case (cell_idx)
            4'd0: glyph_sel = 5'd0;                          // U+97F3
            4'd1: glyph_sel = 5'd1;                          // U+91CF
            4'd2: glyph_sel = 5'd4 + {1'b0, vol_digit};      // 1..5
            4'd3: glyph_sel = 5'd14;                         // '/'
            4'd4: glyph_sel = 5'd9;                          // '5'
            4'd5: begin glyph_sel = 5'd0; cell_valid = 1'b0; end  // gap
            4'd6: glyph_sel = 5'd2;                          // U+4EAE
            4'd7: glyph_sel = 5'd3;                          // U+5EA6
            4'd8: glyph_sel = 5'd4 + {1'b0, bright_digit};   // 1..4
            4'd9: glyph_sel = 5'd14;                         // '/'
            default: glyph_sel = 5'd8;                       // '4'
        endcase
    end

    wire [7:0] glyph_base = (glyph_sel << 3) + (glyph_sel << 2);
    wire [7:0] glyph_addr = glyph_base + {4'b0000, row};

    reg [23:0] rgb_q;
    reg [11:0] rom_q;
    reg [3:0]  col_q;
    reg        band_q;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            hsync_out <= 1'b1;
            vsync_out <= 1'b1;
            de_out <= 1'b0;
            pixel_x_out <= 10'd0;
            rgb_q <= 24'd0;
            rom_q <= 12'd0;
            col_q <= 4'd0;
            band_q <= 1'b0;
            line_y <= 12'd0;
            de_q <= 1'b0;
            vs_q <= 1'b1;
        end else begin
            hsync_out <= hsync;
            vsync_out <= vsync;
            de_out <= de;
            pixel_x_out <= pixel_x;
            rgb_q <= rgb_in;
            de_q <= de;
            vs_q <= vsync;
            if (!vsync)
                line_y <= 12'd0;
            else if (de_q && !de)
                line_y <= line_y + 1'b1;

            band_q <= in_band && cell_valid && (col < GLYPH_W);
            if (in_band && cell_valid && (col < GLYPH_W))
                rom_q <= glyph_rom[glyph_addr];
            else
                rom_q <= 12'd0;
            col_q <= col;
        end
    end

    wire banner_hit = band_q && rom_q[11 - col_q];
    assign rgb_out = banner_hit ? TEXT_COLOR : rgb_q;
endmodule
